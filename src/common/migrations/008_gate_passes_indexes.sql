-- Восстановить индексы журнала калитки, если их снесло обрывом питания.
--
-- `executescript` работает вне транзакции: каждая команда фиксируется сама.
-- Обрыв между `CREATE TABLE gate_passes` и созданием индексов оставляет
-- таблицу без них, а повтор миграции упирается в «table already exists» — что
-- считается признаком уже сделанной работы, и версия помечается применённой.
-- Индексы после этого не появятся уже никогда, и заметить это можно только по
-- медленному журналу через полгода.
--
-- Проверено 2026-08-11 воспроизведением обрыва: из трёх индексов не выжил ни
-- один, уцелел лишь автоматический по `frigate_event_id` — он часть таблицы,
-- и защита от повторного открытия обрыва переживает.
--
-- Здесь `IF NOT EXISTS` у каждой команды: миграция обязана переживать
-- собственный обрыв столько раз, сколько потребуется.

CREATE INDEX IF NOT EXISTS ix_gate_passes_created_at ON gate_passes(created_at);
CREATE INDEX IF NOT EXISTS ix_gate_passes_person_name ON gate_passes(person_name);
CREATE INDEX IF NOT EXISTS ix_gate_passes_decision ON gate_passes(decision);
