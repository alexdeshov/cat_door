-- Обстоятельства прохода: откуда человек пришёл и что было со створкой.
--
-- Оба признака появились из разбора живых проходов 2026-08-12.
--
-- `approach` — «издалека» или «вплотную», по первой рамке события. У всех
-- проходов, которые не были приходом снаружи (выход, разворот у калитки,
-- открытие кодом), рамка на старте упиралась в нижний край кадра: человек
-- стоит вплотную и обрезан снизу. У настоящих приходов низ рамки 0.23–0.91.
-- Одиннадцать событий разделились этим признаком без ошибок.
--
-- `gate_state_before` / `gate_state_after` — что сказал обученный классификатор
-- Frigate про створку. Это замена геркону, от которого отказались: тот сказал
-- бы то же самое, но проводом. Столбцы `reed_*` остаются пустыми — геркона
-- нет, и подменять его источник молча нельзя: «открыта по картинке» и «замкнут
-- контакт» ошибаются по-разному.

ALTER TABLE gate_passes ADD COLUMN approach VARCHAR(20);
ALTER TABLE gate_passes ADD COLUMN first_box_bottom FLOAT;
ALTER TABLE gate_passes ADD COLUMN gate_state_before VARCHAR(20);
ALTER TABLE gate_passes ADD COLUMN gate_state_after VARCHAR(20);
